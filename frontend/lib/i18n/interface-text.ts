function preserveWhitespace(value: string, replacement: string) {
  const leading = value.match(/^\s*/u)?.[0] ?? "";
  const trailing = value.match(/\s*$/u)?.[0] ?? "";
  return `${leading}${replacement}${trailing}`;
}

export function translateInterfaceText(
  value: string,
  locale: AppLocale,
): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const exact = locale === "en" ? exactEnglish : exactFrench;
  if (trimmed in exact)
    return preserveWhitespace(value, exact[trimmed as keyof typeof exact]);
  if (locale === "fr") return value;
  let translated = value;
  for (const [pattern, replacement] of fragmentEnglish) {
    translated =
      typeof replacement === "string"
        ? translated.replace(pattern, replacement)
        : translated.replace(pattern, replacement);
  }
  return translated;
}

